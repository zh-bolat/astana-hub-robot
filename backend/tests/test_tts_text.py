"""Текст для синтеза (app/tts_text.py): многоточия, скобки, междометия, числа словами, произношение."""

from __future__ import annotations

import pytest

from app.tts_text import is_filler_only, kk_suffix, normalize_for_tts


@pytest.mark.parametrize(
    ("lang", "text", "spoken"),
    [
        # многоточия, междометия, скобки
        ("ru", "Хм… Кафе работает с 9:00 до 18:00.", "Кафе работает с девяти до восемнадцати."),
        ("ru", "Ммм, лекция в 18:30.", "Лекция в восемнадцать тридцать."),
        ("ru", "Мне нравится... Это отлично!", "Мне нравится. Это отлично!"),
        ("ru", "Кафе на 2 этаже (рядом с лифтом).", "Кафе на втором этаже, рядом с лифтом."),
        ("ru", "Э-э, на 2-м этаже.", "На втором этаже."),
        ("ru", "[happy] Пожалуйста!", "Пожалуйста!"),
        ("ru", "Ну, кафе работает 9:00–18:00.", "Кафе работает с девяти до восемнадцати."),
        # числа: падеж от предлога, порядковые, род
        ("ru", "Подниметесь до 3 этажа.", "Подниметесь до третьего этажа."),
        ("ru", "В здании 3 этажа.", "В здании три этажа."),
        ("ru", "Больше 1500 компаний.", "Больше тысячи пятисот компаний."),
        (
            "ru",
            "Это 1 минута пешком, скидка 15%.",
            "Это одна минута пешком, скидка пятнадцать процентов.",
        ),
        # произношение
        (
            "ru",
            "Пароль от Wi-Fi у ресепшена, в Astana Hub много IT-компаний.",
            "Пароль от вай-фай у ресепшена, в Астана Хаб много ай-ти-компаний.",
        ),
        ("ru", "TikTok-пространство справа.", "Тик-Ток-пространство справа."),
        # казахский: время с падежами, порядковые, сингармонизм
        (
            "kk",
            "Хм... Кафе 9:00-ден 18:00-ге дейін жұмыс істейді.",
            "Кафе тоғыздан он сегізге дейін жұмыс істейді.",
        ),
        ("kk", "Кафе 9:00–18:00 аралығында ашық.", "Кафе тоғыз бен он сегіз аралығында ашық."),
        ("kk", "Дәріс 18:30-да басталады.", "Дәріс он сегіз отызда басталады."),
        ("kk", "Кафе 2-қабатта.", "Кафе екінші қабатта."),
        ("kk", "Кафе 2 қабатта.", "Кафе екінші қабатта."),
        ("kk", "Бізде 3 зал бар.", "Бізде үш зал бар."),
        ("kk", "Wi-Fi құпиясөзі ресепшенде.", "Уай-фай құпиясөзі ресепшенде."),
        ("kk", "Ммм, TikTok кеңістігі оң жақта.", "Тик-Ток кеңістігі оң жақта."),
        # английский: числа как есть, только паузы и междометия
        ("en", "Um... The cafe is open 9:00 to 18:00.", "The cafe is open 9:00 to 18:00."),
        ("en", "The Wi-Fi password (see reception).", "The Wi-Fi password, see reception."),
        # от фразы ничего не осталось — исходный текст
        ("ru", "Ну", "Ну"),
    ],
)
def test_normalize_for_tts(lang, text, spoken):
    assert normalize_for_tts(text, lang) == spoken


def test_v3_tag_survives_nothing_and_is_not_added_here():
    # тег подачи v3 добавляет TTS-провайдер после нормализации; квадратные скобки из текста ответа — вырезаются
    assert normalize_for_tts("[cheerfully] Сәлем!", "kk") == "Сәлем!"


def test_pronunciations_file_extends_dictionary(tmp_path):
    path = tmp_path / "pronunciations.yaml"
    path.write_text(
        "ru:\n  Astana Hub: Астана Хаб плюс\n  coffee: кофе\nkk:\n  IT: ай-ти\n", "utf-8"
    )
    assert (
        normalize_for_tts("В Astana Hub есть coffee.", "ru", path) == "В Астана Хаб плюс есть кофе."
    )
    path.write_text("ru:\n  coffee: кофеёк\n", "utf-8")
    assert normalize_for_tts("Есть coffee.", "ru", path) == "Есть кофеёк."
    # «IT» — с учётом регистра: английское «it» не трогаем
    assert normalize_for_tts("It is IT.", "kk", path) == "It is ай-ти."


@pytest.mark.parametrize(
    ("word", "case", "suffix"),
    [
        ("тоғыз", "abl", "дан"),
        ("бес", "abl", "тен"),
        ("он", "abl", "нан"),
        ("үш", "dat", "ке"),
        ("алты", "dat", "ға"),
        ("сегіз", "loc", "де"),
        ("бір", "ord", "інші"),
        ("алты", "ord", "ншы"),
        ("тоғыз", "ins", "бен"),
    ],
)
def test_kk_suffix_harmony(word, case, suffix):
    assert kk_suffix(word, case) == suffix


def test_filler_only_phrases():
    assert is_filler_only("Хм…") and is_filler_only("Ммм.") and is_filler_only("Э-э,")
    assert not is_filler_only("Ну, кафе справа.") and not is_filler_only("Мне сюда.")
