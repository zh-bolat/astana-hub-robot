"""Язык ответа робота Курултая: язык экрана (ҚАЗ|РУС), а голосом — только явная смена.

Прежнее правило «есть казахская буква — отвечать по-казахски» ошибалось на русских фразах: распознавание пишет имя
робота и названия по-казахски («Ақылтай, расскажи про законы» → kk). Теперь:
- по умолчанию — язык экрана (язык сессии: `hello.lang`, его шлёт робот при смене языка на экране);
- на другой язык — только если фраза явно на нём (фраза без единой казахской приметы — русская): казахских слов больше, чем русских служебных, и они не меньше
  половины фразы (и наоборот). Имена и названия с казахскими буквами (Ақылтай, Құрылтай, Қазақстан) не считаются;
- сменившийся язык становится языком сессии (live запоминает его, робот переключает экран по `user_final.lang`).

У Astana Hub — прежнее правило (`app.lang.utterance_lang`), этот модуль подключает только профиль kurultai.
"""

from __future__ import annotations

from app.lang import KAZAKH_LETTERS, Lang

# Имена и названия: пишутся по-казахски и в русской речи — о языке фразы не говорят (сравнение по началу слова,
# чтобы ловить падежи: «Құрылтайдың», «Ақылтайға»)
NAME_STEMS = (
    "ақылтай",
    "акылтай",
    "құрылтай",
    "курултай",
    "қазақстан",
    "астана",
    "мәжіліс",
    "мажилис",
)

# Казахские слова без особых букв (частицы, вопросы, вежливость)
KK_WORDS = frozenset(
    {"ма", "ме", "ба", "бе", "па", "пе", "деген", "нешеде", "жоқ", "рахмет", "сау", "бол", "сен", "сіз", "мен",
     "бар", "керек", "қандай", "қашан", "қайда", "кім", "неше", "қанша", "туралы", "және", "бұл", "осы", "айтшы",
     "жарайды", "иа", "болады", "ия"}
)  # fmt: skip

# Русские служебные и частые слова, которых нет в казахском («не», «да», «а» — есть и там, их нет в списке)
RU_WORDS = frozenset(
    {"что", "как", "где", "когда", "почему", "зачем", "кто", "какой", "какая", "какое", "какие", "каких", "сколько",
     "расскажи", "расскажите", "скажи", "скажите", "покажи", "это", "этот", "эта", "есть", "ты", "вы", "тебя", "вас",
     "тебе", "вам", "мне", "меня", "мой", "про", "о", "об", "и", "в", "во", "на", "с", "со", "у", "по", "за", "из",
     "для", "до", "от", "или", "но", "ли", "же", "можно", "нужно", "привет", "здравствуйте", "спасибо",
     "пожалуйста", "хорошо", "сейчас", "будет", "был", "была", "были", "его", "её", "их", "она", "они", "мы"}
)  # fmt: skip


def _words(text: str) -> list[str]:
    out = []
    for raw in (text or "").split():
        w = raw.strip(".,!?;:«»\"'()…—–-").lower()
        if w and any("Ѐ" <= ch <= "ӿ" for ch in w):
            out.append(w)
    return out


def _is_name(word: str) -> bool:
    return word.startswith(NAME_STEMS)


def counts(text: str) -> tuple[int, int, int]:
    """(казахских слов, русских слов, слов без имён) — по кириллическим словам фразы."""
    kk = ru = content = 0
    for w in _words(text):
        if _is_name(w):
            continue
        content += 1
        if w in KK_WORDS or any(ch in KAZAKH_LETTERS for ch in w):
            kk += 1
        elif w in RU_WORDS:
            ru += 1
    return kk, ru, content


def answer_lang(text: str, screen_lang: Lang | None) -> Lang:
    """Язык ответа: язык экрана, если фраза не явно на другом языке. Только ru / kk.

    Явно казахская — казахских слов больше, чем русских, и они не меньше половины слов (без имён).
    Явно русская — русских служебных больше, чем казахских, и казахских нет совсем или русских не меньше половины:
    в русской речи обычно нет ни одной казахской приметы, а служебных слов немного («расскажи про … в …»).
    """
    screen: Lang = screen_lang if screen_lang in ("ru", "kk") else "ru"
    kk, ru, words = counts(text)
    content = max(words, 1)
    if kk > ru and kk * 2 >= content:
        return "kk"
    if ru > kk and (kk == 0 or ru * 2 >= content):
        return "ru"
    if kk == 0 and words >= 1:
        # ни одной казахской приметы (буквы ә ғ қ ң ө ұ ү һ і, частицы): распознавание пишет казахский казахскими
        # буквами — значит, фраза русская, даже без служебных слов («Депутаты Курултая») и при экране ҚАЗ
        return "ru"
    return screen
