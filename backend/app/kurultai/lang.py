"""Язык робота Курултая — только кнопка ҚАЗ|РУС на экране (решение владельца 2026-11-07).

Язык речи посетителя не определяется: распознавание путало русский с казахским, и робот отвечал не на том языке.
Язык сессии live — `hello.lang` (робот шлёт его при смене языка на экране), у /v1/chat — `lang` запроса.
Весь ответ — на этом языке: и текст (промпт), и голос (LiveConversation не выбирает голос по фразе), а фраза,
которую модель всё же написала явно на другом языке, отбрасывается (`wrong_language`) — ответ не переключается
посреди. У Astana Hub — прежнее правило (`app.lang.utterance_lang`), этот модуль подключает только профиль kurultai.
"""

from __future__ import annotations

from app.lang import KAZAKH_LETTERS, Lang

# Имена и названия: пишутся по-казахски и в русской речи — о языке фразы не говорят (сравнение по началу слова,
# чтобы ловить падежи: «Құрылтайдың», «Ақылтайға»)
NAME_STEMS = (
    "ақылтай",
    "акылтай",
    "құрылтай",
    "курултай",
    "қазақстан",
    "астана",
    "мәжіліс",
    "мажилис",
)

# Казахские слова без особых букв (частицы, вопросы, вежливость)
KK_WORDS = frozenset(
    {"ма", "ме", "ба", "бе", "па", "пе", "деген", "нешеде", "жоқ", "рахмет", "сау", "бол", "сен", "сіз", "мен",
     "бар", "керек", "қандай", "қашан", "қайда", "кім", "неше", "қанша", "туралы", "және", "бұл", "осы", "айтшы",
     "жарайды", "иа", "болады", "ия"}
)  # fmt: skip

# Русские служебные и частые слова, которых нет в казахском («не», «да», «а» — есть и там, их нет в списке)
RU_WORDS = frozenset(
    {"что", "как", "где", "когда", "почему", "зачем", "кто", "какой", "какая", "какое", "какие", "каких", "сколько",
     "расскажи", "расскажите", "скажи", "скажите", "покажи", "это", "этот", "эта", "есть", "ты", "вы", "тебя", "вас",
     "тебе", "вам", "мне", "меня", "мой", "про", "о", "об", "и", "в", "во", "на", "с", "со", "у", "по", "за", "из",
     "для", "до", "от", "или", "но", "ли", "же", "можно", "нужно", "привет", "здравствуйте", "спасибо",
     "пожалуйста", "хорошо", "сейчас", "будет", "был", "была", "были", "его", "её", "их", "она", "они", "мы"}
)  # fmt: skip


def _words(text: str) -> list[str]:
    out = []
    for raw in (text or "").split():
        w = raw.strip(".,!?;:«»\"'()…—–-").lower()
        if w and any("Ѐ" <= ch <= "ӿ" for ch in w):
            out.append(w)
    return out


def _is_name(word: str) -> bool:
    return word.startswith(NAME_STEMS)


def counts(text: str) -> tuple[int, int, int]:
    """(казахских слов, русских слов, слов без имён) — по кириллическим словам фразы."""
    kk = ru = content = 0
    for w in _words(text):
        if _is_name(w):
            continue
        content += 1
        if w in KK_WORDS or any(ch in KAZAKH_LETTERS for ch in w):
            kk += 1
        elif w in RU_WORDS:
            ru += 1
    return kk, ru, content


def answer_lang(text: str, screen_lang: Lang | None) -> Lang:
    """Язык ответа — язык экрана (ru / kk); текст реплики язык не меняет."""
    return screen_lang if screen_lang in ("ru", "kk") else "ru"


# Фраза ответа «явно не на том языке» — от стольких слов (короткое «Рахмет!» в русском ответе не режем)
WRONG_LANG_MIN_WORDS = 3


def wrong_language(phrase: str, lang: Lang) -> bool:
    """Фраза ответа явно на другом языке, чем ответ: казахская в русском ответе или русская в казахском."""
    kk, ru, words = counts(phrase)
    if words < WRONG_LANG_MIN_WORDS:
        return False
    if lang == "ru":
        return kk > ru and kk * 2 >= words
    if lang == "kk":
        return kk == 0 and ru * 3 >= words
    return False
