_LANG = {"ru": "ru (русский)", "kk": "kk (казахский)", "en": "ru (русский)"}


def _tail(lang: Lang, now: datetime, places: str) -> str:
    block = (
        f"Точки карты, куда ты можешь проводить (place_id: название):\n{places}\n\n"
        if places
        else "Точки карты: на этом роботе нет ни одной — проводить никуда не можешь, guide_to не вызывай.\n\n"
    )
    return (
        f"{block}"
        f"Язык ответа: {_LANG.get(lang, _LANG['ru'])} — весь ответ строго на этом языке.\n"
        f"Сейчас в Астане: {now:%Y-%m-%d %H:%M}."
    )


def realtime_instructions(
    snapshot: str, materials: str, lang: Lang, now: datetime, places: str = ""
) -> str:
    """Инструкции сессии: персона + правила Realtime + материалы + снимок; в конце точки, язык и время."""
    tail = prompts.SNAPSHOT_NOTE + snapshot if snapshot else prompts.NO_SNAPSHOT_NOTE
    block = f"{materials}\n\n" if materials else ""
    return (
        f"{prompts.PERSONA}\n\n{REALTIME_RULES}\n\n{GUIDE_RULE}\n\n{block}{tail}\n\n"
        f"{_tail(lang, now, places)}"
    )


RAG_RULE = """Данные Курултая: ниже — короткая сводка. Подробности (конкретный законопроект и его статус, депутатский
запрос, кто в каком комитете, пункт повестки, докладчик, цифры доклада, статья Регламента, текст справки) —
вызови search_kurultai, перед вызовом ничего не говори. Нашлось — отвечай по найденному; не нашлось — так и скажи.
Вопрос о заседании или документе шире одного факта («расскажи про пункт 2», «что в докладе ВАП», «о чём закон») —
ищи по сути вопроса, а если выдержек не хватило для полного ответа — вызови search_kurultai ещё раз с другой
формулировкой (название документа, докладчик, цифра, по-казахски). Документы есть на русском и казахском — для
ответа подходит любой. Новости, погода и прочее вне Курултая — web_search."""


def realtime_instructions_rag(summary: str, lang: Lang, now: datetime, places: str = "") -> str:
    """Компактные инструкции: персона + правила + сводка (подробности — инструмент search_kurultai)."""
    return (
        f"{prompts.PERSONA}\n\n{REALTIME_RULES}\n\n{GUIDE_RULE}\n\n{RAG_RULE}\n\nСводка:\n{summary}\n\n"
        f"{_tail(lang, now, places)}"
    )


# ---------- дополнения к одному ходу (response.create.response.instructions = инструкции сессии + дополнение) ----------

_OFFER_EXAMPLE = {
    "ru": "«Хотите, провожу вас в {place}?»",
    "kk": "«Қаласаңыз, сізді {place} дейін апарайын ба?»",
}


def offer_addition(place_name: str, lang: Lang) -> str:
    """Предложение проводить — одним предложением в конце этого ответа (docs/kurultai/navigation.md)."""
    example = _OFFER_EXAMPLE.get(lang, _OFFER_EXAMPLE["ru"]).format(place=place_name)
    return (
        "Дополнение к этому ответу: в самом конце одним коротким предложением предложи проводить посетителя в "
        f"«{place_name}» (на языке ответа, например: {example}). guide_to сейчас не вызывай — только если "
        "посетитель согласится в следующей реплике."
    )


def greeting_addition() -> str:
    """visitor_arrived: поздороваться (как kurultai_greeting_turn, но без строки языка — она уже в инструкциях)."""
    return (
        "Событие: к роботу подошёл посетитель, он ещё ничего не сказал. Поздоровайся от лица Акылтая, ИИ-помощника "
        "Курултая Республики Казахстан, назови своё имя одной-двумя короткими фразами и предложи задать вопрос. "
        "Инструменты (кроме указанных в дополнении) не вызывай."
    )


_FAIL_REASONS = {
    "no_route": "маршрут не найден — путь перекрыт",
    "obstacle": "на пути препятствие, его не обойти",
    "timeout": "ехали слишком долго и не доехали",
    "api_error": "сбой системы навигации робота",
    "unknown_place": "такой точки нет на карте робота",
}


def navigation_addition(place_name: str, result: str, reason: str | None) -> str:
    """Итог поездки — сервер говорит сам новым ходом после state navigating:false."""
    if result == "arrived":
        return (
            f"Событие: робот привёз посетителя к месту «{place_name}». Скажи одной короткой фразой, что вы на "
            "месте, и назови это место (например: «Мы на месте, это Музей Курултая»). Инструменты не вызывай."
        )
    if result == "stopped":
        return (
            f"Событие: поездку к месту «{place_name}» остановили по просьбе посетителя. Скажи одной короткой "
            "фразой, что остановился и готов помочь дальше. Инструменты не вызывай."
        )
    why = _FAIL_REASONS.get(reason or "", "не удалось проехать")
    return (
        f"Событие: робот не смог доехать до места «{place_name}»: {why}. Скажи одной короткой фразой с "
        "извинением, что проехать не получилось, назови причину простыми словами и предложи обратиться к "
        "сотрудникам. Инструменты не вызывай."
    )
