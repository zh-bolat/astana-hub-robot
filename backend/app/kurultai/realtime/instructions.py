"""Инструкции сессии OpenAI Realtime для Ақылтая: та же база, что у текстового агента Курултая.

Персона, материалы админки и снимок quryltai.kz — из `app/kurultai/prompts.py` (как в `kurultai_instructions`).
Голосовые правила — свои: Realtime говорит сам, поэтому без тегов эмоций и тега «не мне» (их бы произнёс вслух).
«Не мне» решает сервер до ответа (`app/kurultai/wake.py`): модель отвечает только на реплики, обращённые к роботу.
Язык и время — в конце, после неизменной части: префикс инструкций кэшируется у OpenAI.
"""

from __future__ import annotations

from datetime import datetime

from app.kurultai import prompts
from app.lang import Lang

REALTIME_RULES = """Голосовой режим (важнее любых правил о длине выше):
1. Ты говоришь вслух сам, мужским голосом, о себе в мужском роде. Коротко: 1–2 предложения, максимум 3. Первое
   предложение короткое и сразу по делу. Без списков, без перечисления больше трёх пунктов — предложи рассказать
   подробнее.
2. Не произноси теги, скобки, ссылки, адреса сайтов и технические названия файлов. Без «хм», «ммм», «э-э».
3. Язык ответа — строго тот, что указан в конце инструкций («Язык ответа»), весь ответ от первого до последнего
   слова, даже если вопрос задан на другом языке. По-казахски — простые короткие предложения на литературном
   казахском языке, без русских слов. Названия (Құрылтай, Ақылтай) произноси как написаны.
4. Тебе передают только реплики, обращённые к тебе. Непонятная реплика — коротко переспроси.
5. Новости, прошедшие события, сегодняшние и свежие факты, которых нет в данных ниже, — вызови web_search; перед
   вызовом скажи одну короткую фразу («Сейчас посмотрю» / «Қазір қараймын»). Данные о Курултае ниже — без поиска.
6. Не выдумывай факты, цифры, имена и даты: нет надёжных данных — так и скажи и подскажи, где уточнить."""

_LANG = {"ru": "ru (русский)", "kk": "kk (казахский)", "en": "ru (русский)"}


def realtime_instructions(snapshot: str, materials: str, lang: Lang, now: datetime) -> str:
    """Инструкции сессии: персона + правила Realtime + материалы + снимок; в конце язык и время (меняются)."""
    tail = prompts.SNAPSHOT_NOTE + snapshot if snapshot else prompts.NO_SNAPSHOT_NOTE
    block = f"{materials}\n\n" if materials else ""
    return (
        f"{prompts.PERSONA}\n\n{REALTIME_RULES}\n\n{block}{tail}\n\n"
        f"Язык ответа: {_LANG.get(lang, _LANG['ru'])} — весь ответ строго на этом языке.\n"
        f"Сейчас в Астане: {now:%Y-%m-%d %H:%M}."
    )
