"""Обращение к роботу Курултая: отвечает, только если позвали по имени (Ақылтай) или словом «робот».

После обращения — разговор без имени KURULTAI_WAKE_WINDOW_S секунд от конца ответа робота (окно продлевается
каждым ответом и тапом по лицу); дальше снова ждёт обращения. Решает LiveConversation (`addressed` и
`wake_window_s` чат-сервиса профиля); у Astana Hub этих атрибутов нет — поведение прежнее.
"""

from __future__ import annotations

import re

from app.kurultai.websearch import NAME_RE

# «робот», «робота», «роботу», «роботом», «роботе», «роботы», «роботик», «роботқа», «роботым», robot; «бот», «бота»,
# «боту», «ботқа», bot (2026-11-07) — короткие окончания; длинные слова («робототехника», «роботизация», «ботинок»)
# — не обращение.
ROBOT_RE = re.compile(
    r"\b(?:робот[а-яёәғқңөұүһі]{0,3}|бот[а-яёәғқңөұүһі]{0,3}|robot|bot)\b", re.IGNORECASE
)


# Обрезанное распознаванием имя одним словом («Ақыл», «Акыл») — тоже зов; внутри фразы «ақыл» — обычное слово
_SHORT_NAME_ALONE = re.compile(r"^\W*а[кқ]ыл\W*$", re.IGNORECASE)


def is_addressed(text: str | None) -> bool:
    """В реплике есть обращение к роботу: имя (как его записывает распознавание) или слово «робот»."""
    if not text:
        return False
    return bool(NAME_RE.search(text) or ROBOT_RE.search(text) or _SHORT_NAME_ALONE.match(text))
